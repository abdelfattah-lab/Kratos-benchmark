from structure.exp import Experiment, ExperimentFactory
from structure.arch import ArchFactory
from structure.design import Design
from util.formatting import pretty, gen_time_elapsed
from util.external_notifs import notification_backend
from typing import Type, TypeVar, Callable, Any

import os
from timeit import default_timer as timer
from typing import Type, TypeVar
from concurrent.futures import ThreadPoolExecutor, as_completed
import pandas as pd
import traceback

E = TypeVar('E', bound=Experiment)
T = TypeVar('T')

class Runner():
    """
    Runs a list of Experiments as generated by an ExperimentFactory.
    """
    def __init__(self):
        """
        Prepare the Runner to accept new experiments via add_experiments().
        """
        self.factory = ExperimentFactory()
        self.experiments: list[E] = []

    def add_experiments(self, experiment_class: Type[E], arch: ArchFactory, design: Design, params: dict[str, any]):
        """
        Add experiments to the Runner's list. All experiments will be threaded by the same ThreadPoolExecutor.

        Required arguments:
        * experiment_class:Type[Experiment], concrete Experiment class to use
        * arch:ArchFactory, concrete ArchFactory to use
        * design:Design, concrete Design to use
        * params:dict, parameters to use
        """
        self.experiments += self.factory.gen_experiments(experiment_class, arch, design, params)
    
    def clear_experiments(self):
        """
        Clear all added experiments.
        """
        self.experiments.clear()

    def run_all_threaded(self,
            only_store_successes: bool = True,
            verbose: bool = False,
            track_run_time: bool = True,
            notify: str = '',
            notify_batch: int = 50,
            desc: str = 'run', 
            num_parallel_tasks: int = 1,
            runner_err_file: str = 'runner.err',
            results_status_key: str = 'status',
            filter_params: list[str] = None,
            filter_results: list[str] = None,
            result_kwargs: dict = {},
            use_formal_name_as_key: bool = False,
        ) -> dict[str, pd.DataFrame]:
        """
        Main function: run all generated experiments with a thread pool.

        Optional arguments:
        * only_store_successes:bool, will not add to results if the experiment failed. Default: True
        * verbose:bool, prints detailed report of each result if True. Default: False
        * track_run_time:bool, will track total run time and print at the end if True. Default: True
        * notify:string, will send failure/batched success updates to the specified notifier. Default: '' means no notifications.
        * notify_batch:int, (only valid if notify is True) send an update every ? experiments run. Failures are sent individually. Default: 50
        * desc:str, description of run
        * num_parallel_tasks:int, maximum number of simultaneous threads allowed in the thread pool.
        * runner_err_file:str, name of error file created by runner if an exception occurs while running the Experiment. Created in the Experiment folder.
        * results_status_key:str, key in results dictionary from the Experiment that should yield a True/False value, indicating success/failure. Default: 'status'
        * filter_params:list[str], a list of parameter keys that should be extracted from the Experiment parameters and included in the resultant Dataframe. Pass None to include all. Default: None
        * filter_results:list[str], a list of result keys that should be extracted from the result and included in the resultant Dataframe. Pass None to include all. Default: None
        * result_kwargs:dict, kwargs to pass into each Experiment get_result() function. Default: empty, i.e., no kwargs. 
        * use_formal_name_as_key: bool, return dictionary uses Experiment.design.get_formal_name() as the key instead of experiment root directory. Default: False
        
        @returns a dictionary of (experiment root directory / Experiment.design.get_formal_name() if use_formal_name_as_key): (Pandas DataFrame with filtered parameters and results).
        """
        # sanity checks.
        if notify and notify_batch <= 0:
            raise ValueError("notify_batch must be an integer value of at least 1!")

        # print experiment count.
        total_count = len(self.experiments)
        print(f"Running '{desc}': Found {total_count} experiment(s).")

        # log start time.
        start_time = timer()
        exp_start_times = {}

        # runnable
        def run_experiment(exp: Experiment) -> tuple[dict, dict]:
            if track_run_time:
                # log start time of experiment
                nonlocal exp_start_times
                exp_start_times[exp] = timer()

            exp.run()
            print(f"Starting next experiment at location {exp.exp_dir}")
            exp.wait()
            return exp.get_full_params(), exp.get_result(**result_kwargs)
        
        # submit all Experiments into the ThreadPoolExecutor
        executor = ThreadPoolExecutor(max_workers=num_parallel_tasks)
        futures_dict = { executor.submit(run_experiment, exp): exp for exp in self.experiments }

        # track successes
        successes = 0

        # collect all results
        results = {}
        def add_to_results(res_dict: dict[str, any], search_dict: dict[str, any], keys: list[str]):
            """
            Recursively search a nested dictionary and add required leaf keys to a result dictionary.
            """
            for k, v in search_dict.items():
                if isinstance(v, dict):
                    add_to_results(res_dict, v, keys)
                elif keys is None or k in keys:
                    res_dict[k] = v

        for i, future in enumerate(as_completed(futures_dict.keys())):
            exp: Experiment = futures_dict[future]
            try:
                result_no = i+1
                result = future.result()
                inp, out = result

                # search for required keys and add to results
                res_dict = {}
                add_to_results(res_dict, inp, filter_params)
                add_to_results(res_dict, out, filter_results)

                is_success = out.get(results_status_key, False)
                if is_success:
                    successes += 1

                # notify Telegram if enabled
                if notify and ((is_success and result_no % notify_batch == 0) or not is_success):
                    msg = f"Run '{desc}': "
                    if is_success:
                        msg += f"{result_no}/{total_count} experiment(s) run, {successes} succeeded."
                    else:
                        msg += f"failed experiment {result_no} @ root directory {exp.root_dir}:\n{pretty(res_dict, 1, to_string=True)}"
                    
                    if track_run_time:
                        time_diff = timer() - start_time
                        est_time_left = time_diff / result_no * (total_count - result_no)
                        msg += f"\n(Estimated time left: {gen_time_elapsed(est_time_left)})"
                    
                    notification_backend(notify, msg)

                if not only_store_successes or is_success:
                    results_key = exp.design.get_formal_name() if use_formal_name_as_key else exp.root_dir
                    if results_key in results:
                        results[results_key].append(res_dict)
                    else:
                        results[results_key] = [res_dict]
                
                if verbose:
                    print("====================================")
                    print(f"Result {result_no}/{total_count}: {'succeeded' if is_success else 'failed'}")
                    if track_run_time:
                        print(f" (Time elapsed for this experiment: {gen_time_elapsed(timer() - exp_start_times[exp])})")

                    print(f"@ root directory {exp.root_dir}")
                    print(f"@ experiment directory {exp.exp_dir}")
                    pretty(res_dict, 1)
                    print("====================================")
                else:
                    print(f"Progress: {i+1}/{total_count} complete ({successes} succeeded)", end='\r', flush=True)
                                
            except Exception as e:
                err_str = f"Exception:\n{traceback.format_exc()}\n"
                with open(os.path.join(exp.exp_dir, runner_err_file), 'w') as f:
                    f.write(err_str)
                
                if verbose:
                    print("!-----------------------------------")
                    print(f"For experiment with directory {exp.exp_dir}, an exception occurred:")
                    print(err_str)
                    print("------------------------------------")
            
        executor.shutdown()

        # print summary
        summary = f"*********************** Run '{desc}' complete! ***********************"
        len_top_line = len(summary)
        summary += f"\nTotal: {total_count}, of which {successes} succeeded ({(successes / total_count * 100):.2f}%)."
        if track_run_time:
            summary += f"\nRun time: {gen_time_elapsed(timer() - start_time)}."
        summary += "\n" + "*" * len_top_line

        print(summary)
        if notify:
            notification_backend(notify, summary)

        return { k: pd.DataFrame.from_records(v) for k, v in results.items() }

class MultiArchRunner:
    """
    Runs experiment functions across multiple architecture configurations in parallel.

    This class enables parallel execution across different ArchFactory classes,
    rather than just parallelizing experiments within a single architecture.

    Usage:
        mar = MultiArchRunner(num_arch_workers=3)

        # Define a function that runs experiments for one architecture
        def run_for_arch(arch_class, arch_config, shared_args):
            # ... run experiments, return DataFrame or result
            return df

        # Add multiple architectures with their configs
        mar.add_task("dcc3", DCC3ArchFactory, {"name": "dcc3", ...}, shared_args)
        mar.add_task("lut_skip", LUTSkipDCC3ArchFactory, {"name": "lut_skip", ...}, shared_args)

        # Run all in parallel
        results = mar.run_all(run_for_arch)
        # results = {"dcc3": df1, "lut_skip": df2, ...}
    """

    def __init__(self, num_arch_workers: int = 2):
        """
        Initialize the MultiArchRunner.

        Args:
            num_arch_workers: Maximum number of architectures to run in parallel.
        """
        self.num_arch_workers = num_arch_workers
        self.tasks: list[tuple[str, Type[ArchFactory], dict, Any]] = []

    def add_task(
        self,
        task_name: str,
        arch_class: Type[ArchFactory],
        arch_config: dict,
        shared_args: Any = None,
    ):
        """
        Add an architecture task to be executed.

        Args:
            task_name: Unique identifier for this task (used as key in results).
            arch_class: The ArchFactory class to use.
            arch_config: Configuration dictionary for this architecture.
            shared_args: Any additional arguments to pass to the runner function.
        """
        self.tasks.append((task_name, arch_class, arch_config, shared_args))

    def clear_tasks(self):
        """Clear all added tasks."""
        self.tasks.clear()

    def run_all(
        self,
        runner_fn: Callable[[Type[ArchFactory], dict, Any], T],
        verbose: bool = False,
        track_run_time: bool = True,
    ) -> dict[str, T]:
        """
        Execute all architecture tasks in parallel.

        Args:
            runner_fn: A callable that takes (arch_class, arch_config, shared_args)
                      and returns a result (typically a DataFrame or dict).
            verbose: Print detailed progress if True.
            track_run_time: Track and print total execution time.

        Returns:
            Dictionary mapping task_name to the result from runner_fn.
        """
        if not self.tasks:
            print("MultiArchRunner: No tasks to run.")
            return {}

        total_count = len(self.tasks)
        print(f"MultiArchRunner: Running {total_count} architecture(s) with {self.num_arch_workers} worker(s).")

        start_time = timer()
        results: dict[str, T] = {}

        def execute_task(task: tuple) -> tuple[str, T]:
            task_name, arch_class, arch_config, shared_args = task
            if verbose:
                print(f"MultiArchRunner: Starting task '{task_name}'...")
            result = runner_fn(arch_class, arch_config, shared_args)
            if verbose:
                print(f"MultiArchRunner: Completed task '{task_name}'.")
            return task_name, result

        with ThreadPoolExecutor(max_workers=self.num_arch_workers) as executor:
            futures = {executor.submit(execute_task, task): task[0] for task in self.tasks}

            for i, future in enumerate(as_completed(futures)):
                task_name = futures[future]
                try:
                    name, result = future.result()
                    results[name] = result
                    print(f"MultiArchRunner: Progress {i+1}/{total_count} - '{name}' complete.")
                except Exception as e:
                    print(f"MultiArchRunner: Task '{task_name}' failed with exception: {e}")
                    traceback.print_exc()

        if track_run_time:
            print(f"MultiArchRunner: All tasks complete in {gen_time_elapsed(timer() - start_time)}.")

        return results


def run_parallel_arch_experiments(
    arch_configs: list[tuple[str, Type[ArchFactory], dict]],
    runner_fn: Callable[[Type[ArchFactory], dict], T],
    num_workers: int = 2,
    verbose: bool = False,
) -> dict[str, T]:
    """
    Convenience function to run experiments across multiple architectures in parallel.

    This is a simpler interface when you don't need to pass shared_args.

    Args:
        arch_configs: List of (task_name, arch_class, arch_config) tuples.
        runner_fn: Function that takes (arch_class, arch_config) and returns a result.
        num_workers: Number of parallel workers.
        verbose: Print progress messages.

    Returns:
        Dictionary mapping task_name to result.

    Example:
        configs = [
            ("dcc3", DCC3ArchFactory, {"name": "dcc3"}),
            ("lut_skip", LUTSkipDCC3ArchFactory, {"name": "lut_skip"}),
        ]

        def run_stress_test(arch_class, arch_config):
            # ... run your experiments
            return result_df

        results = run_parallel_arch_experiments(configs, run_stress_test, num_workers=3)
    """
    mar = MultiArchRunner(num_arch_workers=num_workers)
    for task_name, arch_class, arch_config in arch_configs:
        mar.add_task(task_name, arch_class, arch_config, None)

    # Wrap runner_fn to ignore shared_args
    def wrapped_fn(arch_class, arch_config, _):
        return runner_fn(arch_class, arch_config)

    return mar.run_all(wrapped_fn, verbose=verbose)